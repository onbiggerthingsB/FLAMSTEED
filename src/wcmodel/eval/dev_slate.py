"""The FROZEN development-slate rule (OA Plan 2 v2, V0 / Codex finding 9).

Frozen before any coverage was inspected, and implemented here exactly once so
the config comment, the generator script and the V8 lock all describe the same
selection. Competition KEYS are an evidence choice; fixture SELECTION within
them is this rule and nothing else.

2026-08-01 PRE-LOCK RULE CORRECTION (Codex batch-1 finding 9, RATIFIED):
"excluding any fixture in the scored pools' windows" became EXACT
SCORED-FIXTURE MEMBERSHIP — exclude precisely the scored fixtures by
canonical ``match_id`` (the frozen ``config/oa_scored_inventory.yaml``),
never by calendar window. The euro2024 window blanketed Copa America 2024,
killing an entire eligible development competition that shares not one
fixture with the scored pools. dev_ids ∩ scored_ids = ∅ is asserted at
manifest generation (:func:`eligible_dev_fixtures`) AND at select time
(:func:`truncate_to_n_dev`).
"""
from __future__ import annotations

from datetime import date
from pathlib import Path

import pandas as pd
import yaml

from wcmodel.config import load_config

#: The rule, verbatim. Pinned by tests — editing it is a prereg amendment, not
#: a refactor (this text is the 2026-08-01 pre-lock correction, ratified).
THE_RULE = (
    "every completed senior men's international in the probed competitions "
    "with kickoff in [2022-01-01, 2025-12-31], excluding every fixture in "
    "the frozen scored inventory (exact scored-fixture membership by "
    "canonical fixture identity, config/oa_scored_inventory.yaml), ordered "
    "chronologically, truncated to the first N_dev with admissible coverage")

DEV_WINDOW = (date(2022, 1, 1), date(2025, 12, 31))

#: The CONFIRMATORY pools' calendar windows. KEPT for other consumers (the
#: dev-ledger guard names its pools from these; reporting labels them) but —
#: per the 2026-08-01 correction above — NO LONGER used for dev exclusion:
#: that is exact membership in the scored inventory, nothing else.
SCORED_POOL_WINDOWS = (
    ("wc2022", date(2022, 11, 20), date(2022, 12, 18)),
    ("euro2024", date(2024, 6, 14), date(2024, 7, 14)),
    ("wc2026", date(2026, 6, 11), date(2026, 7, 19)),
)

#: The committed scored-fixture inventory (generated by
#: ``scripts/oa_scored_inventory.py``, hash-bound into the V8 lock). Repo-root
#: anchored like ``aliases.ALIAS_PATH``: no consumer owns the cwd.
SCORED_INVENTORY_PATH = (Path(__file__).resolve().parents[3] / "config"
                         / "oa_scored_inventory.yaml")

_COLUMNS = ("match_id", "date", "home_team", "away_team",
            "home_score", "away_score", "tournament")


class DevSlateError(ValueError):
    """The slate cannot be built as specified — refuse rather than yield a
    slate whose size or membership silently differs from the rule."""


def load_dev_slate_config() -> dict:
    """The `oa_dev_slate:` block. Its window/exclusions must agree with the
    constants above; the generator asserts that before emitting."""
    return load_config()["oa_dev_slate"]


def load_scored_inventory(path: Path = SCORED_INVENTORY_PATH) -> dict:
    """The committed scored-fixture inventory, validated: a malformed or
    empty inventory must never silently exclude nothing."""
    doc = yaml.safe_load(Path(path).read_text()) or {}
    fixtures = doc.get("fixtures")
    if not isinstance(fixtures, list) or not fixtures:
        raise DevSlateError(
            f"{path}: expected a non-empty 'fixtures' list — an empty scored "
            "inventory excludes nothing, which reads as 'no scored fixtures "
            "exist' rather than 'the artifact is broken'")
    ids = [f.get("match_id") for f in fixtures]
    if not all(isinstance(i, str) and i for i in ids):
        raise DevSlateError(f"{path}: every fixture needs a match_id")
    if len(set(ids)) != len(ids):
        raise DevSlateError(f"{path}: duplicate match_id in the inventory")
    return doc


def scored_fixture_ids(path: Path = SCORED_INVENTORY_PATH) -> frozenset:
    """The exclusion set: canonical identities of every scored fixture."""
    return frozenset(f["match_id"]
                     for f in load_scored_inventory(path)["fixtures"])


def _completed(frame: pd.DataFrame) -> pd.Series:
    """A played fixture: both scores present, finite, non-negative, integral.
    A float score is a parse artefact, not a 2.5-goal match — the same
    convention the Elo path applies."""
    ok = pd.Series(True, index=frame.index)
    for col in ("home_score", "away_score"):
        goals = pd.to_numeric(frame[col], errors="coerce")
        ok &= goals.notna() & (goals >= 0) & (goals == goals.round())
    return ok


def eligible_dev_fixtures(results: pd.DataFrame, *, competitions,
                          window=DEV_WINDOW, scored_ids=None) -> pd.DataFrame:
    """The rule up to (not including) truncation: filtered and ORDERED.

    Truncation needs coverage admissibility, which does not exist until the
    odds are acquired — so it is a separate step (``truncate_to_n_dev``) and
    this one is fully determined pre-acquisition.

    Scored exclusion is EXACT MEMBERSHIP (2026-08-01 correction): a row whose
    ``match_id`` is in the frozen scored inventory is out, whatever its date
    or label; a row that is not — Copa America 2024 inside the old euro2024
    window — stays in. ``scored_ids=None`` loads the committed inventory."""
    competitions = list(competitions)
    if not competitions:
        raise DevSlateError(
            "no competitions given: the slate's competition keys are a "
            "coverage-evidence choice and must be set explicitly — an empty "
            "set silently yields an empty slate that reads as 'no coverage'")
    missing = [c for c in _COLUMNS if c not in results.columns]
    if missing:
        raise DevSlateError(f"results frame missing column(s) {missing}")
    scored_ids = scored_fixture_ids() if scored_ids is None else \
        frozenset(scored_ids)
    frame = results.copy()
    # Unquoted YAML/parquet dates arrive as date, datetime or str: one padded
    # ISO form for the comparisons AND the manifest (same idiom as
    # eval/regulation.py).
    frame["date"] = pd.to_datetime(frame["date"]).dt.date
    keep = (frame["tournament"].isin(competitions)
            & (frame["date"] >= window[0]) & (frame["date"] <= window[1])
            & _completed(frame)
            & ~frame["match_id"].isin(scored_ids))
    frame = frame[keep]
    dupes = frame["match_id"].duplicated()
    if dupes.any():
        raise DevSlateError(
            "duplicate match_id(s) in the candidate slate — the manifest is "
            f"keyed by it:\n{frame[frame['match_id'].duplicated(keep=False)]}")
    # The generation-time half of the amendment's assertion — trivially true
    # by construction, asserted anyway so a refactor that drops the mask
    # cannot pass silently.
    overlap = set(frame["match_id"]) & scored_ids
    if overlap:
        raise DevSlateError(
            f"dev candidates intersect the scored inventory: "
            f"{sorted(overlap)[:5]} — dev_ids ∩ scored_ids must be empty")
    # Chronological, then match_id: same-day fixtures need a tie-break or the
    # order inherits whatever the store handed us. match_id is a content hash
    # of fixture identity — arbitrary, but stable and pre-committed.
    return frame.sort_values(["date", "match_id"], kind="mergesort") \
                .reset_index(drop=True)


def truncate_to_n_dev(ordered: pd.DataFrame, *, admissible, n_dev: int,
                      scored_ids=None) -> pd.DataFrame:
    """"...truncated to the first N_dev with admissible coverage."

    ``admissible`` is the set of match_ids with an admissible cut quote (and,
    downstream, a solver success). Refuses rather than returning a short slate:
    the manifest is hash-bound into the V8 lock, so N_dev is a pre-registered
    quantity, never a yield.

    SELECT-TIME half of the amendment's assertion: dev_ids ∩ scored_ids = ∅
    is re-checked here, so a hand-edited manifest smuggling a scored fixture
    past the generator still refuses at the moment of selection."""
    scored_ids = scored_fixture_ids() if scored_ids is None else \
        frozenset(scored_ids)
    ids = set(ordered["match_id"])
    tainted = sorted(ids & scored_ids)
    if tainted:
        raise DevSlateError(
            f"ordered slate contains scored fixture(s) {tainted[:5]} — "
            "dev_ids ∩ scored_ids must be empty at select time (2026-08-01 "
            "pre-lock correction, finding 9)")
    stray = sorted(set(admissible) - ids)
    if stray:
        raise DevSlateError(
            f"admissible id(s) {stray} are not in the ordered slate — the "
            "coverage input and the rule disagree about which fixtures exist")
    covered = ordered[ordered["match_id"].isin(set(admissible))]
    if len(covered) < n_dev:
        raise DevSlateError(
            f"only {len(covered)} fixture(s) have admissible coverage but "
            f"N_dev is {n_dev}: truncating short would change a "
            "pre-registered quantity after the fact")
    return covered.head(n_dev).reset_index(drop=True)
